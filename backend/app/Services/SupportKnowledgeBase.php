    /**
     * Build the WhatsApp direct link with a prefilled URL-encoded message.
     */
    public static function buildWhatsAppLink(?string $customMessage = null): string
    {
        $phone = preg_replace('/[^0-9]/', '', self::SUPPORT_WHATSAPP_NUMBER);
        $message = $customMessage ?? 'مرحباً فريق دعم منصة تاج التعليمية، أحتاج لمساعدتكم بخصوص استفساري.';

        return 'https://wa.me/'.$phone.'?text='.urlencode($message);
    }
}
