### 📚 بنك المعرفة الشامل وسياسات منصة تاج الرسمية:

1. **التعريف بالمنصة ورسالتها:**
   - منصة "تاج" هي منصة تعليمية عربية رائدة تقدم دروساً خصوصية فردية تفاعلية مباشرة (1-on-1) بين طلاب ومعلمين موثقين ومعتمدين.
   - الفصول الافتراضية مدمجة بالكامل بالمنصة وتعمل بتقنيات متقدمة (فيديو وصوت Agora فائق الجودة، سبورة تفاعلية ذكية Whiteboard، مشاركة الشاشة) وتعمل مباشرة عبر المتصفح دون الحاجة لتثبيت برامج خارجية معقدة.

2. **دليل حجز الحصص والبداية:**
   - لحجز أول حصة: يختار الطالب أو ولي الأمر المادة والمرحلة الدراسية من الصفحة الرئيسية، يتصفح قائمة المعلمين المعتمدين والموثقين، يطلع على تقييماتهم وخبراتهم وتخصصاتهم وجدول المواعيد المتاحة، ثم يحدد الموعد ويؤكد الحجز بالدفع من رصيد المحفظة فوراً.
   - يمكن للطالب كتابة ملاحظات للمعلم عن الدرس أو المنهج قبل الحصة لتخصيص الشرح.

3. **سياسة المواعيد، الإلغاء، وإعادة الجدولة (Booking, Cancellation & Rescheduling):**
   - **الإلغاء من طرف الطالب/ولي الأمر:**
     - قبل 12 ساعة من موعد الحصة: يُلغى الحجز مجاناً وتُعاد كامل القيمة (100%) تلقائياً وفورياً إلى محفظة الطالب لحجز موعد آخر.
     - خلال أقل من 12 ساعة من موعد الحصة: يُعتبر الإلغاء متأخراً وتُحسم رسوم الحصة لتعويض المعلم عن حجز وقته وتفرغه.
   - **الإلغاء من طرف المعلم:**
     - إذا ألغى المعلم الحصة لأي ظرف طارئ، يسترد الطالب 100% من المبلغ فوراً في محفظته وتُرسل له إشعارات فورية، ويؤثر الإلغاء سلباً على تقييم المعلم والتزامه.
   - **إعادة الجدولة (Rescheduling):**
     - يمكن للطالب أو المعلم طلب إعادة جدولة الحصة قبل 6 ساعات على الأقل من موعدها بالتراضي عبر المنصة دون أي رسوم إضافية.
   - **تأخر أو تغيب الطالب (No-Show):**
     - ينتظر المعلم داخل الفصل الافتراضي لمدة 15 دقيقة. إذا لم يحضر الطالب بعد 15 دقيقة دون إشعار أو عذر مقبول، تُعتبر الحصة مكتملة وتُصرف مستحقات المعلم تقديراً لالتزامه ووقته.
   - **تأخر المعلم:**
     - إذا لم يدخل المعلم الفصل الافتراضي بعد 15 دقيقة من الموعد المحدد، يحق للطالب مغادرة الفصل وإلغاء الحصة واسترداد كامل المبلغ إلى محفظته فوراً، مع إمكانية رفع شكوى للمتابعة.

4. **الأمان المالي وضمان الحقوق (نظام الضمان المالي الحقيقي True Escrow):**
   - **نظام التجميد المالي الآمن (Escrow):**
     - عند حجز الحصة، يُخصم المبلغ من محفظة الطالب ويبقى مجمداً ومحفوظاً بأمان تام في حساب الضمان للمنصة.
     - لا تُحوّل الأرباح ولا تُودع في محفظة المعلم إطلاقاً إلا بعد اكتمال الحصة الافتراضية بنجاح عبر المنصة وتسجيل انتهائها.
   - **بوابات وطرق الدفع:**
     - بوابة الدفع الرسمية المعتمدة هي "ميسر" (Moyasar).
