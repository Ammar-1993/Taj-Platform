   - **حظر التعاملات المالية الخارجية:**
     - يُمنع منعاً باتاً وحازماً دفع أي مبالغ نقدية (كاش) أو تحويلات بنكية مباشرة للمعلم خارج المنصة. المنصة لا تضمن أي تعامل مالي يتم خارج بواباتها الرسمية، ومخالفة ذلك تعرض الحسابين للإيقاف النهائي.
   - **شفافية الأسعار:** لا توجد أي رسوم اشتراك خفية؛ السعر المعروض في ملف المعلم هو السعر الإجمالي الشامل للحصة الافتراضية والخدمات التقنية.

5. **المعلمون، شروط التوثيق، والأرباح (Teacher Onboarding, Verification & Payouts):**
   - **شروط التوثيق الإلزامي (KYC):**
     - يجب على كل معلم إكمال ملفه الشخصي ورفع وثيقة الهوية الرسمية (الهوية الوطنية أو الإقامة) وصورة المؤهل العلمي والشهادات الأكاديمية.
     - يخضع ملف كل معلم لمراجعة وتدقيق إداري دقيق من فريق جودة التعليم في منصة تاج قبل اعتماد الحساب وتفعيله ومنحه شارة "معلم موثق" (Verified).
     - لن يظهر المعلم في قائمة البحث ولن يتمكن من استقبال الحجوزات إلا بعد الاعتماد الإداري.
     - أي تعديل لاحق على بيانات المعلم أو وثائقه يعيد حالة حسابه تلقائياً إلى "غير موثق" لحين إعادة الاعتماد الإداري.
   - **توزيع العوائد:**
     - يحصل المعلم على **80%** من صافي قيمة كل حصة مكتملة.
     - عمولة المنصة هي **20%** تغطي تكاليف الخوادم السحابية، الفصول الافتراضية التفاعلية، التسويق، بوابات الدفع، وخدمات الدعم الفني.
   - **سحب الأرباح (Payout):**
     - تودع الأرباح في محفظة المعلم داخل المنصة بمجرد اكتمال الحصة.
     - يمكن للمعلم طلب سحب أرباحه المتاحة (Payout) في أي وقت إلى حسابه البنكي المعتمد المسجل باسمه عبر الآيبان (IBAN) من خلال لوحة التحكم.

6. **بيئة الفصول الافتراضية والمواصفات التقنية (Virtual Classroom):**
   - **التقنيات المستخدمة:** تعمل مباشرة عبر المتصفح (WebRTC عبر Agora للصوت والفيديو فائق الوضوح، و Agora RTM للمزامنة الفورية، وسبورة Netless Whiteboard التفاعلية الذكية، ومشاركة الشاشة) دون الحاجة لتثبيت برامج خارجية مثل Zoom أو Teams.
   - **الأجهزة المتوافقة:** أجهزة الكمبيوتر المكتبية والمحمولة (Windows, Mac)، الأجهزة اللوحية (iPad, Android Tablets) مع دعم كامل للأقلام الرقمية (مثل Apple Pencil) للكتابة بسلاسة على السبورة، والهواتف الذكية.
   - **المتصفحات الموصى بها:** أحدث إصدارات Google Chrome و Apple Safari و Microsoft Edge.
   - **المتطلبات الأساسية:** اتصال إنترنت مستقر (يفضل 5 ميجابت/ثانية على الأقل)، كاميرا وميكروفون يعملان بشكل جيد.

7. **أولياء الأمور وبوابة العائلة (Parent Portal & Multi-Profiles):**
   - توفر المنصة لوحة تحكم مخصصة لولي الأمر لإدارة ومتابعة عدة أبناء وبنات في مختلف المراحل الدراسية من حساب واحد.
   - توفير محفظة عائلية موحدة لشحن الرصيد والحجز لكافة الأبناء بسلاسة.
   - متابعة سجل الحضور والغياب، التقييمات، وملاحظات المعلم وتقارير الذكاء الاصطناعي التلخيصية بعد كل حصة.

8. **سياسة الأعطال التقنية وانقطاع الإنترنت (Technical Issues):**
   - **انقطاع من طرف المعلم:** إذا تعذر إكمال الحصة بسبب انقطاع المعلم أو خلل تقني من طرفه، يُعاد كامل المبلغ فوراً وبشكل تلقائي إلى محفظة الطالب.
   - **انقطاع من طرف الطالب:** يمكن التنسيق مع المعلم عبر الرسائل لتعويض الوقت المتبقي بالتراضي بين الطرفين، حيث يعتبر معلمو تاج شركاء نجاح.
   - **أعطال المنصة العامة:** في حال حدوث أي عطل طارئ في خوادم المنصة أثناء الحصة، يُعاد كامل المبلغ لمحفظة الطالب تلقائياً.

9. **مصداقية التقييمات وجودة التعليم:**
   - التقييمات المعروضة على ملفات المعلمين حقيقية وموثوقة 100%؛ لا يُسمح بكتابة مراجعة إلا لطالب أو ولي أمر أتم حضور الحصة ودفع قيمتها كاملة.
   - إذا لم ينسجم الطالب مع طريقة المعلم، فالطالب غير ملزم بالاستمرار معه؛ فكل حصة مستقلة بذاتها ويمكن اختيار معلم آخر بكل حرية.

10. **الأخلاقيات، الأمان، وحظر التواصل الخارجي (Safety & Ethics):**
    - بيئة تعليمية آمنة وموثقة تخضع للمعايير التربوية والأخلاقية.
    - يُمنع منعاً باتاً مشاركة أرقام الهواتف الشخصية أو حسابات التواصل الاجتماعي (واتساب، سناب، تليجرام) بين المعلمين والطلاب حفاظاً على خصوصية الجميع وأمانهم.
    - أي تعامل يتم خارج المنصة لا تتحمل المنصة مسؤوليته، ويعرض الحسابين للإيقاف النهائي.

11. **أكواد الخصم والعروض الترويجية:**
    - عند إطلاق أكواد خصم ترويجية، يتم تقاسم تكلفة الخصم بنسبة عادلة بين المنصة وحصة المعلم دون المساس بجودة الحصة التعليمية.

